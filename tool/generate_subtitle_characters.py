"""Regenerate unambiguous CJK script characters using OpenCC (Apache-2.0).

Requires opencc. These sets are recognition evidence, not a text converter.
"""
from pathlib import Path
from opencc import OpenCC

s2t, t2s = OpenCC("s2t"), OpenCC("t2s")
simplified, traditional = [], []
for code in range(0x4E00, 0xA000):
    char = chr(code)
    # Exclude one-to-many mappings and characters that change both ways.
    simp, trad = t2s.convert(char), s2t.convert(char)
    if simp == char and len(trad) == 1 and trad != char:
        simplified.append(char)
    if trad == char and len(simp) == 1 and simp != char:
        traditional.append(char)

target = Path(__file__).resolve().parents[1] / "lib/services/quality/subtitle_characters.dart"
with target.open("w", encoding="utf-8", newline="\n") as output:
    output.write("// Generated by tool/generate_subtitle_characters.py using OpenCC (Apache-2.0).\n")
    output.write("// OpenCC copyright (c) 2010-2024 BYVoid and contributors.\n")
    for name, chars in [("simplifiedEvidenceCharacters", simplified), ("traditionalEvidenceCharacters", traditional)]:
        output.write(f"const {name} =\n")
        for offset in range(0, len(chars), 70):
            output.write("    '" + "".join(chars[offset:offset+70]) + "'" + (";" if offset+70 >= len(chars) else "") + "\n")
print(f"Generated {len(simplified)} simplified and {len(traditional)} traditional characters")
